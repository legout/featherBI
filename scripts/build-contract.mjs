/** Build the strict runtime v2 standalone validator. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import ajvModule from "ajv";
import standaloneModule from "ajv/dist/standalone/index.js";

const Ajv = ajvModule.default ?? ajvModule;
const standaloneCode =
 standaloneModule.standaloneCode ??
 standaloneModule.default ??
 standaloneModule;
const rootDir = path.resolve(
 path.dirname(fileURLToPath(import.meta.url)),
 "..",
);
const outDir = path.join(rootDir, ".generated");
await mkdir(outDir, { recursive: true });

const schemaPath = path.join(rootDir, "contract", "schema-v2.json");
const outPath = path.join(outDir, "validate-config-v2.mjs");
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
const runtimeImports = [];
let helperIndex = 0;
const moduleCode = standaloneCode(ajv, validate).replaceAll(
 /require\("([^"]+)"\)/g,
 (_match, specifier) => {
  const resolved = /\.[a-z]+$/.test(specifier) ? specifier : `${specifier}.js`;
  const local = `__ajvRuntime${helperIndex++}`;
  runtimeImports.push(`import ${local} from "${resolved}";`);
  return local;
 },
);
if (runtimeImports.length === 0 && /\brequire\s*\(/.test(moduleCode)) {
 throw new Error("generated contract 2 validator contains require()");
}
await writeFile(
 outPath,
 [
  `// Generated by scripts/build-contract.mjs from ${path.relative(rootDir, schemaPath)} — DO NOT EDIT.`,
  ...runtimeImports,
  moduleCode,
  "",
 ].join("\n"),
);
const { default: generatedValidate } = await import(
 pathToFileURL(outPath).href
);
const minimal = JSON.parse(
 await readFile(
  path.join(rootDir, "tests", "fixtures", "minimal.config.json"),
  "utf8",
 ),
);
if (!generatedValidate(minimal)) {
 throw new Error("generated contract 2 validator rejected the minimal config");
}
for (const unsupported of [1, 3]) {
 if (generatedValidate({ ...minimal, contract: unsupported })) {
  throw new Error(
   `generated contract 2 validator accepted contract ${unsupported}`,
  );
 }
}
console.log(`wrote ${outPath}`);
