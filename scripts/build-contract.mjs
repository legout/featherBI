/**
 * Build-time generator for the shared config validator.
 *
 * Compiles contract/schema.json with Ajv 8.20.0 standalone code generation into
 * .generated/validate-config.mjs. The CLI and browser bundles import that
 * generated module; no schema compilation happens at runtime.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import ajvModule from "ajv";
import standaloneModule from "ajv/dist/standalone/index.js";

const Ajv = ajvModule.default ?? ajvModule;
const standaloneCode =
 standaloneModule.standaloneCode ??
 standaloneModule.default ??
 standaloneModule;

const rootDir = path.resolve(
 path.dirname(fileURLToPath(import.meta.url)),
 "..",
);
const schemaPath = path.join(rootDir, "contract", "schema.json");
const outDir = path.join(rootDir, ".generated");
const outPath = path.join(outDir, "validate-config.mjs");

const schema = JSON.parse(await readFile(schemaPath, "utf8"));

const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
if (typeof validate !== "function") {
 throw new Error(
  "Ajv did not produce a validation function for contract/schema.json",
 );
}

// Ajv 8 standalone ESM output still references its runtime helpers through
// require() (see ajv#2133). Rewrite those references to static ESM imports so
// the generated module needs no runtime CommonJS interop. A default import of
// a CJS module is module.exports itself, so an optional `.default` suffix in
// the generated expression keeps resolving to the same value. This is a
// build-time textual transform: the emitted module stays plain static code.
const runtimeImports = [];
let helperIndex = 0;
const moduleCode = standaloneCode(ajv, validate).replaceAll(
 /require\("([^"]+)"\)/g,
 (_match, specifier) => {
  // ESM resolution needs an explicit file extension; Ajv's helper specifiers
  // are extension-less CommonJS paths.
  const resolved = /\.[a-z]+$/.test(specifier) ? specifier : `${specifier}.js`;
  const local = `__ajvRuntime${helperIndex++}`;
  runtimeImports.push(`import ${local} from "${resolved}";`);
  return local;
 },
);
if (runtimeImports.length === 0 && /\brequire\s*\(/.test(moduleCode)) {
 throw new Error(
  "generated validator still contains require() calls that were not rewritten",
 );
}

const generated = [
 "// Generated by scripts/build-contract.mjs from contract/schema.json — DO NOT EDIT.",
 `// Ajv standalone validator for ${schema.$id}`,
 ...runtimeImports,
 moduleCode,
 "",
].join("\n");

await mkdir(outDir, { recursive: true });
await writeFile(outPath, generated, "utf8");

// Smoke check: the generated module must run without runtime schema compilation.
const { default: generatedValidate } = await import(
 pathToFileURL(outPath).href
);
const minimal = JSON.parse(
 await readFile(
  path.join(rootDir, "tests", "fixtures", "minimal.config.json"),
  "utf8",
 ),
);
if (generatedValidate(minimal) !== true) {
 throw new Error("generated validator rejected the minimal example config");
}
if (generatedValidate({ ...minimal, contract: 2 }) !== false) {
 throw new Error(
  "generated validator accepted an unsupported contract version",
 );
}

console.log(`wrote ${outPath}`);
