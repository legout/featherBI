/** Build the strict runtime v1 and v2 standalone validators. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import ajvModule from "ajv";
import standaloneModule from "ajv/dist/standalone/index.js";

const Ajv = ajvModule.default ?? ajvModule;
const standaloneCode = standaloneModule.standaloneCode ?? standaloneModule.default ?? standaloneModule;
const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(rootDir, ".generated");
await mkdir(outDir, { recursive: true });

for (const [version, filename] of [[1, "schema.json"], [2, "schema-v2.json"]]) {
 const schemaPath = path.join(rootDir, "contract", filename);
 const outPath = path.join(outDir, `validate-config-v${version}.mjs`);
 const schema = JSON.parse(await readFile(schemaPath, "utf8"));
 const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
 const validate = ajv.compile(schema);
 const runtimeImports = [];
 let helperIndex = 0;
 const moduleCode = standaloneCode(ajv, validate).replaceAll(
  /require\("([^"]+)"\)/g,
  (_match, specifier) => {
   const resolved = /\.[a-z]+$/.test(specifier) ? specifier : `${specifier}.js`;
   const local = `__ajvRuntime${helperIndex++}`;
   runtimeImports.push(`import ${local} from "${resolved}";`);
   return local;
  },
 );
 if (runtimeImports.length === 0 && /\brequire\s*\(/.test(moduleCode)) {
  throw new Error(`generated contract ${version} validator contains require()`);
 }
 await writeFile(outPath, [
  `// Generated by scripts/build-contract.mjs from contract/${filename} — DO NOT EDIT.`,
  ...runtimeImports,
  moduleCode,
  "",
 ].join("\n"));
 const { default: generatedValidate } = await import(pathToFileURL(outPath).href);
 const minimal = JSON.parse(await readFile(path.join(rootDir, "tests", "fixtures", "minimal.config.json"), "utf8"));
 if (version === 2) {
  minimal.theme = "neutral";
  minimal.layout = minimal.layout.map((component, index) => ({
   ...component,
   ...(component.x !== undefined ? { xField: component.x } : {}),
   ...(component.y !== undefined ? { yField: component.y } : {}),
   x: 1,
   y: index + 1,
   width: 12,
   height: 1,
  }));
 }
 if (!generatedValidate({ ...minimal, contract: version })) {
  throw new Error(`generated contract ${version} validator rejected the minimal config`);
 }
 if (generatedValidate({ ...minimal, contract: version === 1 ? 2 : 1 })) {
  throw new Error(`generated contract ${version} validator accepted the other version`);
 }
 console.log(`wrote ${outPath}`);
}
