/**
 * Test-only harness page builder for Plan 02 browser tests.
 *
 * Bundles `tests/browser/harness.mjs` (which imports the runtime bootstrap)
 * with esbuild into a single self-contained `.artifacts/browser/harness.html`
 * opened over `file://`. This artifact is never production output: the
 * production viewer bundle is a separate future build.
 *
 * `npm run build:harness` always regenerates the contract validator and the
 * synthetic fixtures first, then rebuilds this page from source, so a stale
 * harness can never be reused by `npm run test:browser`.
 */

import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import * as esbuild from "esbuild";
import {
 DUCKDB_WASM_BUNDLES,
 DUCKDB_WASM_VERSION,
} from "../runtime/bootstrap.mjs";

const rootDir = path.resolve(
 path.dirname(fileURLToPath(import.meta.url)),
 "..",
);
const entryPoint = path.join(rootDir, "tests", "browser", "harness.mjs");
const outDir = path.join(rootDir, ".artifacts", "browser");
const outPath = path.join(outDir, "harness.html");

const bundle = await esbuild.build({
 entryPoints: [entryPoint],
 bundle: true,
 format: "iife",
 platform: "browser",
 target: "chrome130",
 minify: false,
 write: false,
 legalComments: "none",
 logLevel: "warning",
});
const code = bundle.outputFiles[0].text;
const codeSha256 = createHash("sha256").update(code).digest("hex");

// Runtime asset pins must stay visible in the built harness metadata.
const buildMeta = {
 generator: "scripts/build-test-harness.mjs",
 builtAt: new Date().toISOString(),
 bundleSha256: codeSha256,
 entryPoint: "tests/browser/harness.mjs",
 runtimeBootstrap: "runtime/bootstrap.mjs",
 duckdbWasm: {
  version: DUCKDB_WASM_VERSION,
  bundles: DUCKDB_WASM_BUNDLES,
 },
 testOnly: true,
};

const html = `<!doctype html>
<!-- featherBI test-only harness: generated by scripts/build-test-harness.mjs. Never ship this file. -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>featherBI browser test harness (test-only)</title>
</head>
<body>
<h1>featherBI browser test harness</h1>
<p id="harness-status" data-state="loading">harness loading…</p>
<script>window.__featherbiHarnessBuild = ${JSON.stringify(buildMeta)};</script>
<script>
${code}
</script>
</body>
</html>
`;

await mkdir(outDir, { recursive: true });
await writeFile(outPath, html, "utf8");

console.log(`wrote ${outPath}`);
console.log(
 `bundle sha256=${codeSha256} duckdb-wasm=${DUCKDB_WASM_VERSION} (pinned remote assets)`,
);
