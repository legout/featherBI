const rootDir = path.resolve(
 path.dirname(fileURLToPath(import.meta.url)),
 "..",
);
const outDir = path.join(rootDir, ".artifacts", "browser");
const outPath = path.join(outDir, "harness.html");

const bundle = await esbuild.build({
 entryPoints: [path.join(rootDir, "tests", "browser", "harness.mjs")],
 bundle: true,
 format: "iife",
 platform: "browser",
 target: "chrome130",
 minify: false,
 write: false,
 legalComments: "none",
 logLevel: "warning",
});
const code = bundle.outputFiles[0].text;
const codeSha256 = createHash("sha256").update(code).digest("hex");
const buildMeta = {
 generator: "scripts/build-test-harness.mjs",
 builtAt: new Date().toISOString(),
 bundleSha256: codeSha256,
 entryPoint: "tests/browser/harness.mjs",
 runtimeBootstrap: "runtime/bootstrap.mjs",
 duckdbWasm: { version: DUCKDB_WASM_VERSION, bundles: DUCKDB_WASM_BUNDLES },
 testOnly: true,
};
const html = `<!doctype html>
<!-- featherBI test-only harness: generated by scripts/build-test-harness.mjs. Never ship this file. -->
<html lang="en"><head><meta charset="utf-8"><title>featherBI browser test harness (test-only)</title></head>
<body><h1>featherBI browser test harness</h1><p id="harness-status" data-state="loading">harness loading…</p>
<script>window.__featherbiHarnessBuild = ${scriptJson(buildMeta)};</script><script>\n${code}\n</script></body></html>`;
await mkdir(outDir, { recursive: true });
await writeFile(outPath, html, "utf8");

const fixtureConfig = parseJson(
 await readFile(
  path.join(rootDir, "tests/fixtures/runtime.config.json"),
  "utf8",
 ),
 "runtime fixture config",
);
