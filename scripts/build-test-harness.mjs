function parseJson(text, label) {
 try {
  return JSON.parse(text);
 } catch (error) {
  throw new Error(`invalid JSON in ${label}: ${error.message}`, {
   cause: error,
  });
 }
}

function scriptJson(value) {
 return JSON.stringify(value).replaceAll("<", "\\u003c");
}
