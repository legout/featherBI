/**
 * Live Iceberg tables by metadata URI (spec 2026-09-28-0004 §2.2, LT-05,
 * LT-06, LT-08): a `remote: {kind: iceberg, metadataUri}` source stages its
 * candidate generation through the pinned trusted Iceberg capability with
 * true snapshot/delete semantics — never a raw read_parquet over the data
 * files. The authored versioned metadata JSON is a fixed pointer: Refresh
 * re-reads the same document and never chases a newer one; a failed refresh
 * retains the prior active generation with a visible source-specific error.
 *
 * The fixture is the hand-crafted Iceberg v2 table generated by
 * tests/fixtures/generate.py: one data file with rows A/B/C and a positional
 * delete file deleting B. The raw data file alone (what naive Parquet staging
 * would read) exposes three rows; the dashboard view must expose exactly the
 * two surviving rows.
 */

