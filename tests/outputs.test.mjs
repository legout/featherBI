// Output modes at the CLI (spec 0001 §Outputs and §Determinism): byte-identical rebuilds and the 25 MB warning.
// The rejection of --offline with --split is covered by the rejection cases in validate.test.mjs.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const cli = path.join(root, "skill/featherbi/scripts/featherbi.mjs");

const sha256 = file => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const build = (args, cwd) => spawnSync(process.execPath, [cli, "build", ...args], { cwd, encoding: "utf8" });
// A source of `rows` incompressible rows (random doubles), generated by DuckDB at build time: no fixture file.
const big = rows => `title: Big
name: big
sources:
  big:
    read: "(SELECT random() AS x FROM range(${rows}))"
tiles:
  - { type: kpi, title: Rows, sql: "SELECT COUNT(*) AS value FROM big" }
`;

test("two consecutive builds are byte-identical in every output mode", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "outputs-determinism-"));
  try {
    const file = ["--out", path.join(dir, "<out>", "dashboard.html")];
    const modes = [
      [["--out", path.join(dir, "<out>", "dashboard.html")], ["dashboard.html"]],
      [["--split", "--out", path.join(dir, "<out>")], ["index.html", "sales.parquet"]],
      [["--offline", ...file], ["dashboard.html"]],
    ];
    for (const [args, files] of modes) {
      for (const out of ["a", "b"]) {
        const r = build(["fixtures/hand/pivot-table.yaml", ...args.map(a => a.replace("<out>", out))], root);
        assert.equal(r.status, 0, r.stderr);
      }
      assert.deepEqual(fs.readdirSync(path.join(dir, "b")), fs.readdirSync(path.join(dir, "a")));
      assert.deepEqual(files.map(f => sha256(path.join(dir, "b", f))), files.map(f => sha256(path.join(dir, "a", f))), args.join(" "));
    }
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test("the build warns above 25 MB of embedded Parquet and recommends --split", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "outputs-warning-"));
  try {
    const run = rows => {
      fs.writeFileSync(path.join(dir, "dashboard.yaml"), big(rows));
      return build(["dashboard.yaml"], dir);
    };
    const small = run(1_000);
    assert.equal(small.status, 0, small.stderr);
    assert.doesNotMatch(small.stderr, /25 MB/);

    const large = run(4_500_000); // ~30 MB of zstd Parquet: random doubles do not compress
    assert.equal(large.status, 0, large.stderr);
    assert.ok(fs.statSync(path.join(dir, "dist/big.html")).size > 25 * 2 ** 20, "the fixture really is above the limit");
    assert.match(large.stderr, /25 MB/);
    assert.match(large.stderr, /--split/);

    const split = build(["dashboard.yaml", "--split", "--out", "split"], dir); // nothing is embedded, so there is nothing to warn about
    assert.equal(split.status, 0, split.stderr);
    assert.doesNotMatch(split.stderr, /25 MB/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
